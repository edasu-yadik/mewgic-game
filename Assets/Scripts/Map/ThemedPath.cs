        internal static float Lane(int region, int panel, float y)
        {
            var sample = Samples[region];
            if (sample == null)
                return .5f;

            float row = Mathf.Clamp01(y) * 8;
            int i = Mathf.Min(7, Mathf.FloorToInt(row));
            int start = panel * 9;
            float a = sample[start + Mathf.Max(0, i - 1)] * .01f;
            float b = sample[start + i] * .01f;
            float c = sample[start + i + 1] * .01f;
            float d = sample[start + Mathf.Min(8, i + 2)] * .01f;
            float t = row - i, t2 = t * t;
            return .5f * ((2 * b) + (-a + c) * t +
                (2 * a - 5 * b + 4 * c - d) * t2 + (-a + 3 * b - 3 * c + d) * t2 * t);
        }
